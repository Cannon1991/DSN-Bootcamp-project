def load_and_preprocess_data():
    # 1. Load Data from string buffers instead of files
    train = pd.read_csv(io.StringIO(train_data_string))
    test = pd.read_csv(io.StringIO(test_data_string))

    train_len = len(train)
    target = train['total_sales'].values

    train = train.drop(columns=['total_sales'])
    df = pd.concat([train, test], axis=0).reset_index(drop=True)

    # 2. Fix Inconsistent Categorical Capitalizations
    df['product_category'] = df['product_category'].astype(str).str.upper().str.strip()
    df['fat_content'] = df['fat_content'].astype(str).str.replace('LF', 'Low Fat').str.replace('low fat', 'Low Fat').str.replace('reg', 'Regular').str.strip()

    # 3. Handle Missing Values
    item_weight_map = df.groupby('product_code')['product_weight_kg'].mean()
    df['product_weight_kg'] = df['product_weight_kg'].fillna(df['product_code'].map(item_weight_map))
    df['product_weight_kg'] = df['product_weight_kg'].fillna(df['product_weight_kg'].mean())

    # Safely extract mode for store size mapping
    store_size_map = df.groupby('store_format')['store_size'].apply(lambda x: x.mode().iloc[0] if not x.mode().empty else 'Medium').to_dict()
    df['store_size'] = df['store_size'].fillna(df['store_format'].map(store_size_map))

    visibility_mean = df[df['shelf_visibility'] > 0]['shelf_visibility'].mean() if not df[df['shelf_visibility'] > 0].empty else 0.05
    df['shelf_visibility'] = df['shelf_visibility'].replace(0, visibility_mean)

    # 4. Feature Engineering
    category_price_mean = df.groupby('product_category')['product_price'].transform('mean')
    df['price_to_category_ratio'] = df['product_price'] / category_price_mean
    df['product_type_prefix'] = df['product_code'].apply(lambda x: str(x)[:3])
    df['store_size_format'] = df['store_size'].astype(str) + "_" + df['store_format'].astype(str)

    # 5. Categorical Encoding
    categorical_cols = ['fat_content', 'product_category', 'store_code', 'store_size',
                        'store_location_tier', 'store_format', 'product_type_prefix', 'store_size_format']

    for col in categorical_cols:
        le = LabelEncoder()
        df[col] = le.fit_transform(df[col].astype(str))

    X_train = df.iloc[:train_len].drop(columns=['id', 'product_code'])
    X_test = df.iloc[train_len:].drop(columns=['id', 'product_code'])
    test_ids = df.iloc[train_len:]['id'].values

    return X_train, target, X_test, test_ids

def train_and_evaluate():
    print("⏳ Preprocessing sample slices from memory...")
    X, y, X_test, test_ids = load_and_preprocess_data()

    # Since the sample split size is small, adjusted folds to 3 for structural evaluation safety
    n_splits = 3
    kf = KFold(n_splits=n_splits, shuffle=True, random_state=42)
    oof_preds = np.zeros(len(X))
    test_preds = np.zeros(len(X_test))

    print(f"🚀 Training cross-validation ensemble loop...")
    for fold, (train_idx, val_index) in enumerate(kf.split(X, y)):
        X_train_f, y_train_f = X.iloc[train_idx], y[train_idx]
        X_val_f, y_val_f = X.iloc[val_index], y[val_index]

        model1 = RandomForestRegressor(n_estimators=50, max_depth=5, random_state=42, n_jobs=-1)
        model2 = GradientBoostingRegressor(n_estimators=50, max_depth=4, learning_rate=0.1, random_state=42)

        model1.fit(X_train_f, y_train_f)
        model2.fit(X_train_f, y_train_f)

        val_pred = (model1.predict(X_val_f) + model2.predict(X_val_f)) / 2
        oof_preds[val_index] = val_pred

        fold_test_pred = (model1.predict(X_test) + model2.predict(X_test)) / 2
        test_preds += fold_test_pred / n_splits

        fold_rmse = root_mean_squared_error(y_val_f, val_pred)
        print(f"✅ Fold {fold + 1} Validation RMSE: {fold_rmse:.4f}")

    overall_rmse = root_mean_squared_error(y, oof_preds)
    print(f"\n📊 Total Sample Cross-Validated RMSE Score: {overall_rmse:.4f}")

    submission = pd.DataFrame({
        'id': test_ids,
        'total_sales': test_preds
    })
    print("\n📦 Predicted outputs showcase for test set:")
    print(submission.to_string(index=False))

if __name__ == '__main__':
    train_and_evaluate()

