def feature_engineering_pipeline(train_path='train.csv', test_path='test.csv'):
    train = pd.read_csv(train_path)
    test = pd.read_csv(test_path)

    train_len = len(train)
    y_train = train['total_sales'].values

    train_df = train.drop(columns=['total_sales'])
    combined_df = pd.concat([train_df, test], axis=0).reset_index(drop=True)

    # 1. Clean inconsistent syntax capitalizations [1, 2]
    combined_df['product_category'] = combined_df['product_category'].astype(str).str.upper().str.strip()
    combined_df['fat_content'] = (combined_df['fat_content']
                                  .astype(str)
                                  .str.replace('LF', 'Low Fat')
                                  .str.replace('low fat', 'Low Fat')
                                  .str.replace('reg', 'Regular')
                                  .str.strip())

    # 2. Impute product weights by code group mapping [1, 2]
    weight_lookup = combined_df.groupby('product_code')['product_weight_kg'].transform('mean')
    combined_df['product_weight_kg'] = combined_df['product_weight_kg'].fillna(weight_lookup)
    combined_df['product_weight_kg'] = combined_df['product_weight_kg'].fillna(combined_df['product_weight_kg'].mean())

    # 3. Impute missing store sizes using format trends [1, 2]
    format_size_mode = combined_df.groupby('store_format')['store_size'].transform(
        lambda x: x.mode().iloc if not x.mode().empty else 'Medium'
    )
    combined_df['store_size'] = combined_df['store_size'].fillna(format_size_mode)

    # 4. Correct structural 0.0 values in product shelf visibility [1, 2]
    valid_visibility_mean = combined_df[combined_df['shelf_visibility'] > 0]['shelf_visibility'].mean()
    combined_df['shelf_visibility'] = combined_df['shelf_visibility'].replace(0, valid_visibility_mean)

    # 5. Extract domain feature markers [1, 2]
    cat_price_mean = combined_df.groupby('product_category')['product_price'].transform('mean')
    combined_df['price_deviation_from_cat'] = combined_df['product_price'] - cat_price_mean
    combined_df['price_to_category_ratio'] = combined_df['product_price'] / cat_price_mean
    combined_df['product_class_prefix'] = combined_df['product_code'].apply(lambda x: str(x)[:3])
    combined_df['store_footprint_profile'] = combined_df['store_size'].astype(str) + "_" + combined_df['store_format'].astype(str)
    combined_df['visibility_price_index'] = combined_df['shelf_visibility'] * combined_df['product_price']

    # 6. Apply Label Encoding across categorical splits [1, 2]
    cat_encoded_fields = ['fat_content', 'product_category', 'store_code', 'store_size',
                          'store_location_tier', 'store_format', 'product_class_prefix', 'store_footprint_profile']

    for field in cat_encoded_fields:
        encoder = LabelEncoder()
        combined_df[field] = encoder.fit_transform(combined_df[field].astype(str))

    X_train = combined_df.iloc[:train_len].drop(columns=['id', 'product_code'])
    X_test = combined_df.iloc[train_len:].drop(columns=['id', 'product_code'])
    test_identifiers = combined_df.iloc[train_len:]['id'].values

    return X_train, y_train, X_test, test_identifiers

def execute_ensemble_training():
    X, y, X_test, test_ids = feature_engineering_pipeline()

    # Using 3 splits for safe CV sizing with current segment arrays
    num_folds = 3
    kf = KFold(n_splits=num_folds, shuffle=True, random_state=42)

    oof_predictions = np.zeros(len(X))
    final_test_predictions = np.zeros(len(X_test))

    print(f"📊 Training Ensemble models across {num_folds} validation folds...")

    for fold, (train_idx, val_idx) in enumerate(kf.split(X, y)):
        X_tr, y_train_f = X.iloc[train_idx], y[train_idx]
        X_va, y_val_f = X.iloc[val_idx], y[val_idx]

        # LightGBM Regressor [1, 2]
        lgb_model = lgb.LGBMRegressor(
            n_estimators=500, max_depth=6, learning_rate=0.05,
            subsample=0.8, colsample_bytree=0.8, random_state=42 + fold, verbose=-1
        )
        lgb_model.fit(X_tr, y_train_f, eval_set=[(X_va, y_val_f)], callbacks=[lgb.early_stopping(30, verbose=False)])

        # XGBoost Regressor [1, 2]
        xgb_model = xgb.XGBRegressor(
            n_estimators=500, max_depth=5, learning_rate=0.05,
            subsample=0.8, colsample_bytree=0.8, random_state=42 + fold, verbosity=0
        )
        xgb_model.fit(X_tr, y_train_f, eval_set=[(X_va, y_val_f)], verbose=False)

        if HAS_CATBOOST:
            cb_model = CatBoostRegressor(iterations=500, depth=5, learning_rate=0.05, random_seed=42 + fold, verbose=0)
            cb_model.fit(X_tr, y_train_f, eval_set=(X_va, y_val_f), early_stopping_rounds=30)

            fold_val = (0.40 * lgb_model.predict(X_va) + 0.30 * xgb_model.predict(X_va) + 0.30 * cb_model.predict(X_va))
            fold_test = (0.40 * lgb_model.predict(X_test) + 0.30 * xgb_model.predict(X_test) + 0.30 * cb_model.predict(X_test))
        else:
            fold_val = (0.50 * lgb_model.predict(X_va) + 0.50 * xgb_model.predict(X_va))
            fold_test = (0.50 * lgb_model.predict(X_test) + 0.50 * xgb_model.predict(X_test))

        oof_predictions[val_idx] = fold_val
        final_test_predictions += fold_test / num_folds

        print(f"  -> Fold {fold + 1} Segment RMSE Evaluation: {root_mean_squared_error(y_val_f, fold_val):.4f}")

    print(f"\n🎯 Cross-Validated Pipeline Ensemble Score: {root_mean_squared_error(y, oof_predictions):.4f}")

    submission_output = pd.DataFrame({'id': test_ids, 'total_sales': final_test_predictions})
    submission_output.to_csv('dsn_mart_submission.csv', index=False)
    print("\n📦 Compiled submission format generated ('dsn_mart_submission.csv'):")
    print(submission_output.to_string(index=False))

if __name__ == '__main__':
    execute_ensemble_training()